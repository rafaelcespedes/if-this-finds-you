// Draws the Reading Room's hand-ruled lines (?rules=hand, an experiment Rafael asked for on 3 Nov) with the
// handwriting engine's own pen, once, into engine-rules.ts. Run again after changing anything here:
// node app/src/themes/reading-room/rules/make-engine-rules.mjs
// Each rule is one stroke of a fine dip pen at low pressure along a ruler: it sets down a touch heavier, lifts with a
// slight taper, wavers by a fraction of a pixel and its ink thins and thickens a little along the way. Drawn in a band
// 4 px tall (40 units, 10 units a pixel) around the 1 px a crisp rule takes, so the layout never moves.
// Two lengths, so the wobble keeps its scale when stretched: short for the ledger's rows (320 px), long for the running
// head, the shelves and the spread (1280 px).
import fs from 'node:fs';
import path from 'node:path';
import * as E from '../../../../../engine/index.js';

const BAND = 40; // units: 4 px
const MID = BAND / 2;
const WIDTH = 12; // the line's mean width in units: 1.2 px
const SETS = { short: { len: 3200, n: 8 }, long: { len: 12800, n: 4 } };

const HAND = E.makeHand('reading-room-rules', 'print');
const PEN = { ...HAND, pen: 'pointed', pressure: 0.25, pressureVar: 0.32, tremor: 0.08 };

/** One ruled line, `len` units long, as an SVG path and its ink density sampled along it (0..1 stops). */
function rule(len, seed) {
  const rnd = E.rng(`rule:${len}:${seed}`);
  // a ruler's line: straight but for a slow sway (a hand pressing the pen against a ruler) of up to half a pixel,
  // the faintest tilt, and ends that stop a pixel or two short of the column's edges
  const span = len / 3200, k1 = (0.6 + rnd() * 1.4) * span, k2 = (2 + rnd() * 3) * span, p1 = rnd() * 6.28, p2 = rnd() * 6.28;
  const amp = 3 + rnd() * 2.5, tilt = (rnd() - 0.5) * 5;
  const x0 = 8 + rnd() * 22, x1 = len - 8 - rnd() * 26;
  const pts = [];
  for (let x = x0; x <= x1; x += 12) {
    const t = (x - x0) / (x1 - x0);
    pts.push([x, MID + tilt * (t - 0.5) + amp * (0.7 * Math.sin(6.283 * k1 * t + p1) + 0.3 * Math.sin(6.283 * k2 * t + p2))]);
  }
  // the pen's own width, scaled so the line averages WIDTH
  let p = { ...PEN, tip: 1 };
  const probe = E.penOutline(p, pts, seed);
  const mean = probe.ink.w.reduce((a, b) => a + b, 0) / probe.ink.w.length;
  p = { ...PEN, tip: WIDTH / mean };
  const o = E.penOutline(p, pts, seed);
  const poly = E.simplify ? E.simplify(o, 0.45) : o;
  const d = 'M' + poly.map(([x, y]) => `${Math.round(x)} ${Math.round(y * 2) / 2}`).join('L') + 'Z';
  // the ink's density along the stroke, as 9 stops (0..1, normalised to its lightest)
  const ink = o.ink, stops = [];
  for (let i = 0; i <= 8; i++) {
    const j = Math.min(ink.n - 1, Math.round((i / 8) * (ink.n - 1)));
    stops.push(ink.d ? ink.d[j] : 1);
  }
  const hi = Math.max(...stops), lo = Math.min(...stops);
  return { d, ink: stops.map((v) => +(hi > lo ? 0.82 + 0.18 * (v - lo) / (hi - lo) : 1).toFixed(2)) };
}

const out = {};
for (const [name, { len, n }] of Object.entries(SETS)) out[name] = { len, rules: Array.from({ length: n }, (_, i) => rule(len, i + 1)) };
const file = path.join(import.meta.dirname, 'engine-rules.ts');
fs.writeFileSync(file,
  `// GENERATED by make-engine-rules.mjs: the Reading Room's hand-ruled lines, drawn with the engine's dip pen.\n` +
  `// Each path sits in a band ${BAND} units tall (4 px) and \`len\` units long; \`ink\` is its density at 9 even stops.\n` +
  `export const BAND = ${BAND};\n` +
  `export const ENGINE_RULES: Record<'short' | 'long', { len: number; rules: { d: string; ink: number[] }[] }> = ${JSON.stringify(out)};\n`);
console.log('wrote', file, Math.round(fs.statSync(file).size / 1024) + ' kB', Object.entries(out).map(([k, v]) => `${k}: ${v.rules.length} × ~${Math.round(v.rules.reduce((a, r) => a + r.d.length, 0) / v.rules.length)} chars`).join(', '));
