// Converts Hershey .jhf files (engine/sources/data/) into engine/sources/hershey-data.js (an ES module).
// Usage: node tools/embed-hershey.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function readJhf(file) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  const out = []; let cur = '';
  for (const line of lines) {
    if (!cur && !line.trim()) continue;
    cur += line;
    const n = parseInt(cur.slice(5, 8), 10);
    if (cur.length - 8 >= n * 2) { out.push(cur); cur = ''; }
  }
  return out;
}
function parseGlyph(s) {
  const n = parseInt(s.slice(5, 8), 10);
  const d = s.slice(8, 8 + n * 2);
  const L = d.charCodeAt(0) - 82, R = d.charCodeAt(1) - 82;
  const strokes = []; let st = [];
  for (let i = 2; i < d.length; i += 2) {
    if (d[i] === ' ' && d[i + 1] === 'R') { if (st.length) strokes.push(st); st = []; continue; }
    st.push([d.charCodeAt(i) - 82, d.charCodeAt(i + 1) - 82]);
  }
  if (st.length) strokes.push(st);
  return { l: L, r: R, s: strokes };
}
const sets = { print: 'futural.jhf', script: 'scripts.jhf' };
const data = {};
for (const [k, f] of Object.entries(sets)) {
  const g = readJhf(path.join(root, 'engine', 'sources', 'data', f));
  data[k] = {};
  // jhf files list ASCII 32..127 in order
  for (let i = 0; i < 95; i++) data[k][String.fromCharCode(32 + i)] = parseGlyph(g[i]);
}
const banner = `// Generated by tools/embed-hershey.mjs from data/futural.jhf (print) and data/scripts.jhf (script).
// Hershey font data: created by Dr. A. V. Hershey at the U.S. National Bureau of Standards;
// .jhf format by James Hurt, Cognition, Inc. See data/hershey-fonts.notes.txt for the use terms.
// Coordinates: Hershey units, y down. Baseline y=9, cap height y=-12. l/r = side bearings.\n`;
const out = path.join(root, 'engine', 'sources', 'hershey-data.js');
fs.writeFileSync(out, banner + 'export default ' + JSON.stringify(data) + ';\n');
console.log('wrote', out, fs.statSync(out).size, 'bytes');
