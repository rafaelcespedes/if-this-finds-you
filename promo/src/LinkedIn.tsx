// The LinkedIn cut (4:5, 1080 × 1350): the launch video's square on top, a strip of the room's colour under it with
// one short line at a time (LinkedIn plays videos muted, so the words say what the pictures show). It combines the
// two videos: the title and the flip to the stop, the letter and its changing forms (the canvas of hands is cut: the
// fonts list does that job, and says they're fonts), the fonts video reframed square, then the title again.
import { useLayoutEffect, useState } from 'react';
import { AbsoluteFill, Sequence, continueRender, delayRender, interpolate, staticFile, useCurrentFrame } from 'remotion';
import { Promo, defaultProps, settingsOf } from './Promo';
import { FontList } from './FontList';
import { plan } from './scene/timeline';
import { SECONDS as FONT_SECONDS } from './scene/fontlist-plan';

const FPS = 30, S = 1080, STRIP = 270;
const P = plan(settingsOf({ ...defaultProps, size: S }, FPS));
const sec = (id: string) => P.sections.find((s) => s.id === id)!;

interface Part { id: string; at: number; from: number; len: number; line: string; lineFrom?: number }
function parts(): Part[] {
  const land = sec('land'), letter = sec('letter'), end = sec('end');
  const out: Part[] = [];
  let at = 0;
  const add = (p: Omit<Part, 'at'>) => { out.push({ ...p, at }); at += p.len; };
  // the title and the flip, to the dead stop (the line comes in after the title)
  add({ id: 'flip', from: 0, len: land.to, line: 'Every hand here is generated by one engine', lineFrom: sec('title').to });
  add({ id: 'letter', from: letter.from, len: letter.to - letter.from, line: 'Real letters, written out by writers who never existed' });
  add({ id: 'fonts', from: 0, len: Math.round(FONT_SECONDS * FPS), line: 'Every hand is a font you can download' });
  add({ id: 'end', from: end.from, len: end.to - end.from, line: 'Free and open source · ifthisfindsyou.app' });
  return out;
}
export const LINKEDIN_PARTS = parts();
export const LINKEDIN_FRAMES = LINKEDIN_PARTS.reduce((a, p) => a + p.len, 0);

let ui: Promise<unknown> | null = null;
const loadUi = () => (ui ??= new FontFace('RR Schibsted', `url(${staticFile('fonts/schibsted-grotesk-latin.woff2')}) format('woff2')`, { weight: '400 900' }).load().then((f) => document.fonts.add(f)));

/** the line under the picture: in over a quarter second, out over a fifth before its part ends */
const Line: React.FC<{ part: Part }> = ({ part }) => {
  const f = useCurrentFrame(); // within the part
  const start = (part.lineFrom ?? 0);
  const o = interpolate(f, [start, start + 8, part.len - 6, part.len], [0, 1, 1, part.id === 'end' ? 1 : 0], { extrapolateLeft: 'clamp', extrapolateRight: 'clamp' });
  return (
    <div style={{ position: 'absolute', left: 0, right: 0, top: S, height: STRIP, display: 'grid', placeItems: 'center', opacity: o }}>
      <div style={{ maxWidth: 920, textAlign: 'center', fontFamily: '"RR Schibsted", system-ui, sans-serif', fontWeight: 500, fontSize: 46, lineHeight: 1.28, letterSpacing: '-0.005em', color: '#1e2733', textWrap: 'balance' as any }}>
        {part.line}
      </div>
    </div>
  );
};

export const LinkedIn: React.FC = () => {
  const [h] = useState(() => delayRender('linkedin fonts'));
  useLayoutEffect(() => { loadUi().then(() => continueRender(h)); }, [h]);
  return (
    <AbsoluteFill style={{ background: '#e6e4de' }}>
      {LINKEDIN_PARTS.map((p) => (
        <Sequence key={p.id} from={p.at} durationInFrames={p.len} layout="none">
          <div style={{ position: 'absolute', left: 0, top: 0, width: S, height: S, overflow: 'hidden' }}>
            {p.id === 'fonts'
              ? <FontList openHand={13} endText="Over a million handwritten fonts" variant="square" w={S} h={S} />
              : (
                <Sequence from={-p.from} layout="none">
                  <Promo {...defaultProps} size={S} audio="none" fpsNow={FPS} />
                </Sequence>
              )}
          </div>
          <Line part={p} />
        </Sequence>
      ))}
    </AbsoluteFill>
  );
};
